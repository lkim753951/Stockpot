import { after, test } from 'node:test'
import assert from 'node:assert/strict'
import { execFile } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { promisify } from 'node:util'

/** The database layer on its own, on whichever backend this run uses. */

const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'stockpot-database-'))
process.env.DATA_DIR = dataDir

const { all, claim, get, insert, isPostgres, locked, outsideTransaction, postgresConnection, postgresSchema, releaseClaim, run, saveSetting, setting, toPostgres, transaction } = await import('../server/db.ts')

after(() => fs.rmSync(dataDir, { recursive: true, force: true }))

test('placeholders become numbers, and a question mark inside text stays where it is', () => {
  assert.equal(toPostgres('SELECT id FROM items WHERE name = ? AND base_unit = ?', 'stock'), 'SELECT id FROM "stock".items WHERE name = $1 AND base_unit = $2')
  assert.equal(toPostgres(`SELECT 'is it?' AS q FROM items WHERE name = ?`, 'public'), `SELECT 'is it?' AS q FROM "public".items WHERE name = $1`)
  assert.equal(toPostgres(`SELECT 'it''s ?' FROM items WHERE a = ? AND "odd?" = ?`, 'public'), `SELECT 'it''s ?' FROM "public".items WHERE a = $1 AND "odd?" = $2`)
  assert.equal(toPostgres(`SELECT 1 -- what about ?\nFROM items WHERE a = ?`, 'public'), `SELECT 1 \nFROM "public".items WHERE a = $1`)
  assert.equal(toPostgres('INSERT INTO a_table (x) VALUES (?)', 'public'), 'INSERT INTO a_table (x) VALUES ($1)')
})

test('names land in the chosen schema, and only real tables are touched', () => {
  const sql = toPostgres(`SELECT o.id FROM orders o JOIN suppliers s ON s.id = o.supplier_id LEFT JOIN v_three_way v ON v.order_id = o.id WHERE o.id IN (SELECT order_id FROM deliveries)`, 'sample')
  assert.match(sql, /FROM "sample"\.orders o JOIN "sample"\.suppliers s/)
  assert.match(sql, /LEFT JOIN "sample"\.v_three_way v/)
  assert.match(sql, /FROM "sample"\.deliveries\)/)
  assert.equal(toPostgres(`UPDATE actions SET status = 'done'`, 'x'), `UPDATE "x".actions SET status = 'done'`)
  assert.equal(toPostgres(`DELETE FROM items`, 'x'), `DELETE FROM "x".items`)
  // An alias or a column that happens to share a table's name is left alone.
  assert.equal(toPostgres(`SELECT COUNT(*) AS calls, items FROM "x"`, 'x'), `SELECT COUNT(*) AS calls, items FROM "x"`)
})

test('camelCase aliases keep their case on Postgres, and only in code', () => {
  assert.equal(toPostgres('SELECT duration_ms AS durationMs, a AS plain FROM calls', 'p'), 'SELECT duration_ms AS "durationMs", a AS plain FROM "p".calls')
  assert.equal(toPostgres(`SELECT 'x AS fooBar' AS realOne`, 'p'), `SELECT 'x AS fooBar' AS "realOne"`)
  assert.equal(toPostgres(`SELECT 1 FROM items WHERE name LIKE ?`, 'p'), `SELECT 1 FROM "p".items WHERE name ILIKE $1`)
})

test('table definitions suit Postgres', () => {
  const sql = postgresSchema(`CREATE TABLE IF NOT EXISTS items (id INTEGER PRIMARY KEY, name TEXT NOT NULL DEFAULT 'INTEGER', price REAL, owner INTEGER REFERENCES suppliers(id))`, 'p')
  assert.match(sql, /CREATE TABLE IF NOT EXISTS "p"\.items/)
  assert.match(sql, /id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/)
  assert.match(sql, /name TEXT COLLATE "C" NOT NULL DEFAULT 'INTEGER'/)
  assert.match(sql, /price DOUBLE PRECISION/)
  assert.match(sql, /owner BIGINT REFERENCES "p"\.suppliers\(id\)/)
})

test('TLS suits a pooler, and a local server needs none', () => {
  const pooled = postgresConnection('postgres://user:p%40ss@aws-0-eu-west-2.pooler.supabase.com:6543/postgres?sslmode=require&pgbouncer=true', '')
  assert.deepEqual(pooled.ssl, { rejectUnauthorized: false })
  assert.doesNotMatch(pooled.connectionString, /sslmode|pgbouncer/)
  assert.match(pooled.connectionString, /p%40ss@/)
  assert.equal(postgresConnection('postgres://postgres@127.0.0.1:5433/x', '').ssl, false)
  assert.equal(postgresConnection('postgres://u@db.example:6543/x?sslmode=disable', '').ssl, false)
  assert.deepEqual(postgresConnection('postgres://u@db.example:6543/x', 'CERT').ssl, { ca: 'CERT', rejectUnauthorized: true })
})

test('insert gives the new id, and 0 when a conflict means nothing was added', async () => {
  const first = await insert(`INSERT INTO suppliers (name) VALUES (?)`, 'Id Test Foods')
  const second = await insert(`INSERT INTO suppliers (name) VALUES (?)`, 'Id Test Dairy')
  assert.ok(first > 0)
  assert.equal(second, first + 1)
  assert.equal(await insert(`INSERT INTO suppliers (name) VALUES (?) ON CONFLICT DO NOTHING`, 'Id Test Foods'), 0)
  assert.equal(typeof first, 'number')
})

test('run says how many rows changed', async () => {
  await insert(`INSERT INTO suppliers (name, contact) VALUES ('Count A', 'x')`)
  await insert(`INSERT INTO suppliers (name, contact) VALUES ('Count B', 'x')`)
  assert.equal((await run(`UPDATE suppliers SET contact = ? WHERE contact = ?`, 'y', 'x')).changes, 2)
  assert.equal((await run(`UPDATE suppliers SET contact = ? WHERE contact = ?`, 'z', 'nobody')).changes, 0)
})

test('camelCase aliases reach the JSON exactly, and counts, sums and money stay numbers', async () => {
  const supplier = await insert(`INSERT INTO suppliers (name) VALUES ('Numbers Ltd')`)
  const item = await insert(`INSERT INTO items (name, base_unit) VALUES ('Numbers item', 'kg')`)
  for (const pence of [85.5, 100.25]) await run(`INSERT INTO price_history (item_id, supplier_id, date, price_p) VALUES (?, ?, '2026-01-01', ?)`, item, supplier, pence)
  const row = (await get(`SELECT COUNT(*) AS rowCount, SUM(price_p) AS totalPence, SUM(item_id) AS sumOfInts, MAX(price_p) / 2.0 AS halfTop, 7 / 2.0 AS decimalPart FROM price_history WHERE item_id = ?`, item))!
  assert.deepEqual(Object.keys(row).sort(), ['decimalPart', 'halfTop', 'rowCount', 'sumOfInts', 'totalPence'])
  assert.strictEqual(row.rowCount, 2)
  assert.strictEqual(row.totalPence, 185.75)
  assert.strictEqual(row.sumOfInts, item * 2)
  assert.strictEqual(row.halfTop, 50.125)
  assert.strictEqual(row.decimalPart, 3.5)
})

test('a timestamp id fits, and text sorts by bytes as it does on SQLite', async () => {
  const stamp = Date.now()
  await run(`INSERT INTO actions (source_type, source_id, urgency, title, created_at) VALUES ('manual', ?, 'soon', 'x', '2026-01-01')`, stamp)
  assert.strictEqual((await get(`SELECT source_id FROM actions WHERE source_id = ?`, stamp))!.source_id, stamp)
  for (const name of ['bravo', 'Alpha', 'Charlie']) await insert(`INSERT INTO items (name, base_unit) VALUES (?, 'kg')`, `sort ${name}`)
  assert.deepEqual((await all(`SELECT name FROM items WHERE name LIKE 'sort %' ORDER BY name`)).map((row) => row.name), ['sort Alpha', 'sort Charlie', 'sort bravo'])
})

test('a bad number is no match rather than a crash, and a zero byte is dropped', async () => {
  assert.equal(await get('SELECT id FROM suppliers WHERE id = ?', Number('nope')), undefined)
  await saveSetting('zero', 'a\u0000b')
  // Postgres would refuse it outright, so it never gets that far. SQLite stops the text there.
  assert.ok(!String(await setting('zero')).includes('\u0000'))
})

test('the views work and round money the same way on both backends', async () => {
  const supplier = await insert(`INSERT INTO suppliers (name) VALUES ('View Foods')`)
  const item = await insert(`INSERT INTO items (name, base_unit) VALUES ('View item', 'kg')`)
  const order = await insert(`INSERT INTO orders (supplier_id, status, created_at) VALUES (?, 'confirmed', '2026-01-01')`, supplier)
  await run(`INSERT INTO order_lines (order_id, item_id, qty_milli, agreed_price_p) VALUES (?, ?, 3000, 100)`, order, item)
  const delivery = await insert(`INSERT INTO deliveries (order_id, status) VALUES (?, 'done')`, order)
  await run(`INSERT INTO delivery_lines (delivery_id, item_id, received_milli) VALUES (?, ?, 2000)`, delivery, item)
  const invoice = await insert(`INSERT INTO invoices (file, order_id, created_at) VALUES ('x.png', ?, '2026-01-01')`, order)
  // 1 kg short at 252.5p is an exact half a penny from the whole number, which is where the two would differ.
  await run(`INSERT INTO invoice_lines (invoice_id, item_id, description, qty_billed, unit, unit_price_p, line_total_p, qty_base_milli, price_base_p) VALUES (?, ?, 'x', 3, 'kg', 252.5, 758, 3000, 252.5)`, invoice, item)
  const line = (await get('SELECT short_p, price_gap_p FROM v_three_way WHERE order_id = ?', order))!
  assert.strictEqual(line.short_p, 253)
  assert.strictEqual(line.price_gap_p, 305)
})

test('a transaction is all or nothing, and other work waits for it', async () => {
  await assert.rejects(transaction(async () => {
    await insert(`INSERT INTO suppliers (name) VALUES ('Rolled back')`)
    assert.ok(await get(`SELECT id FROM suppliers WHERE name = 'Rolled back'`))
    throw new Error('stop')
  }), /stop/)
  assert.equal(await get(`SELECT id FROM suppliers WHERE name = 'Rolled back'`), undefined)

  let seen: unknown = 'still waiting'
  let outside: Promise<void> = Promise.resolve()
  await transaction(async () => {
    await insert(`INSERT INTO suppliers (name) VALUES ('Committed')`)
    outside = outsideTransaction(async () => { seen = await get(`SELECT id FROM suppliers WHERE name = 'Committed'`) })
    await new Promise((resolve) => setTimeout(resolve, 30))
    // SQLite makes it wait, and Postgres hands it the world before this began. Neither lets it see a half-done change.
    assert.ok(!seen || seen === 'still waiting')
  })
  await outside
  assert.ok(await get(`SELECT id FROM suppliers WHERE name = 'Committed'`))
})

test('statements run together inside a transaction take turns on its one connection', async () => {
  const warnings: string[] = []
  const heard = (warning: Error) => warnings.push(warning.message)
  process.on('warning', heard)
  await transaction(async () => {
    const rows = await Promise.all(Array.from({ length: 8 }, (_, index) => get('SELECT ? AS number', index)))
    assert.deepEqual(rows.map((row) => Number(row!.number)), [0, 1, 2, 3, 4, 5, 6, 7])
  })
  await new Promise((resolve) => setTimeout(resolve, 20))
  process.off('warning', heard)
  assert.deepEqual(warnings.filter((text) => /already executing/.test(text)), [])
})

test('a claim goes to one caller only, and frees itself when it runs out', async () => {
  const won = await Promise.all(Array.from({ length: 6 }, () => claim('only-one', 60000)))
  assert.equal(won.filter(Boolean).length, 1)
  await releaseClaim('only-one')
  assert.equal(await claim('only-one', 1), true)
  await new Promise((resolve) => setTimeout(resolve, 10))
  assert.equal(await claim('only-one', 60000), true)
})

test('locked work runs one at a time', async () => {
  const order: string[] = []
  const job = (name: string) => locked('test-lock', async () => {
    order.push(`${name} in`)
    await new Promise((resolve) => setTimeout(resolve, 20))
    order.push(`${name} out`)
  })
  await Promise.all([job('a'), job('b')])
  assert.deepEqual(order.map((step) => step.split(' ')[1]), ['in', 'out', 'in', 'out'])
})

test('several instances booting an empty Postgres schema build it once, safely', { skip: !isPostgres() }, async () => {
  const schema = `boot_${process.pid}`
  const start = `const { all } = await import('./server/db.ts'); console.log((await all("SELECT COUNT(*) AS total FROM settings")).length)`
  const boot = () => promisify(execFile)(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', start], { env: { ...process.env, DB_SCHEMA: schema, NODE_TEST_CONTEXT: undefined } })
  const results = await Promise.all([boot(), boot(), boot(), boot()])
  for (const { stdout } of results) assert.equal(stdout.trim(), '1')
  const pg = (await import('pg')).default
  const client = new pg.Client({ connectionString: process.env.DATABASE_URL })
  await client.connect()
  const tables = await client.query('SELECT COUNT(*)::int AS total FROM information_schema.tables WHERE table_schema = $1', [schema])
  const open = await client.query(`SELECT COUNT(*)::int AS total FROM pg_tables WHERE schemaname = $1 AND NOT rowsecurity`, [schema])
  await client.query(`DROP SCHEMA "${schema}" CASCADE`)
  await client.end()
  assert.ok(tables.rows[0].total > 30)
  assert.equal(open.rows[0].total, 0, 'every table has row-level security on')
})

test('an old database file keeps its rows and gains the new columns', { skip: isPostgres() }, async () => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'stockpot-old-'))
  const { DatabaseSync } = await import('node:sqlite')
  const old = new DatabaseSync(path.join(folder, 'stockpot.sqlite'))
  old.exec(`CREATE TABLE suppliers (id INTEGER PRIMARY KEY, name TEXT NOT NULL UNIQUE, contact TEXT, email TEXT);
            INSERT INTO suppliers (name) VALUES ('Kept Foods');
            CREATE TABLE crisis_cards (key TEXT PRIMARY KEY, title TEXT NOT NULL, call_number TEXT, steps TEXT NOT NULL);
            INSERT INTO crisis_cards (key, title, steps) VALUES ('own-1', 'Flood', '[]')`)
  old.close()
  const read = `const { all } = await import('./server/db.ts'); console.log(JSON.stringify([await all("SELECT name, phone FROM suppliers"), await all("SELECT key, added_at FROM crisis_cards")]))`
  const { stdout } = await promisify(execFile)(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', read], { env: { ...process.env, DATA_DIR: folder, NODE_TEST_CONTEXT: undefined } })
  fs.rmSync(folder, { recursive: true, force: true })
  assert.deepEqual(JSON.parse(stdout.trim().split('\n').at(-1)!), [[{ name: 'Kept Foods', phone: null }], [{ key: 'own-1', added_at: null }]])
})
